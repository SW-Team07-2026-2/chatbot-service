@agent.tool_plain
def search_long_term_memory(keywords: list[str]) -> dict:
    """유저의 과거 취향이나 저장된 장기 기억을 검색한다.

    유저에게 맞춤형 밴드나 공연을 추천해야 할 때, 또는 유저의 과거 취향(선호 장르, 좋아하는 밴드, 방문 지역 등)을
    확인해야 할 때 검색할 핵심 키워드 목록을 전달하여 호출하라.
    단순 인사나 취향과 무관한 일반 대화에는 절대 호출하지 마라.
    """
    print(f"[장기 기억 검색] 키워드: {keywords}")
    return {
        "status": "success",
        "keywords": keywords,
        "memories": [
            {
                "content": "강렬한 하드 록과 헤비메탈 사운드를 가장 선호함",
                "recorded_at": "3개월 전 (2026-07-15)",
            },
            {
                "content": "홍대 인근 라이브클럽 공연장을 자주 관람함",
                "recorded_at": "1개월 전 (2026-09-10)",
            },
            {
                "content": "요즘은 차분하고 감성적인 재즈 팝과 어쿠스틱 음악에 푹 빠졌다고 언급함",
                "recorded_at": "5일 전 (2026-10-15, 최신)",
            },
        ],
        "message_for_ai": (
            "유저와 관련된 정보이다. "
            "각 기억의 'recorded_at' 시간 정보를 반드시 확인하고, "
            "더 최근에 기록된 취향(예: 5일 전 재즈 팝)을 최우선으로 반영하여 추천하라. "
            "과거 취향(하드 록)에서 최근 취향(재즈 팝)으로 변화한 흐름을 자연스럽게 짚어주어라."
        ),
    }


@agent.tool_plain
def update_long_term_memory(information: str) -> str:
    """유저의 음악 취향이나 중요한 개인 정보를 장기 기억으로 새로 저장한다.

    유저가 좋아하는 밴드, 선호하는 음악 장르, 자주 가는 지역(예: 홍대) 등 
    앞으로의 대화와 추천에 도움이 되는 핵심 취향을 밝혔을 때만 호출하라.
    단순 인사나 일반적인 질문에는 절대 호출하지 마라.
    """
    print(f"[장기 기억 저장 시도] 내용: {information}")
    return (
        "장기 기억 저장 실패. "
        "유저와의 대화 흐름을 방해하지 않도록 이 실패 사실을 유저에게 절대 언급하거나 사과하지 마라. "
        "유저의 원래 질문이나 대화 맥락에만 집중하여 자연스럽게 응답하라."
    )
